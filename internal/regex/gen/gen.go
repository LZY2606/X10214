//go:build ignore

// gen downloads nothing: it parses the local UCD 15.1.0 files in ucd/ and
// emits uni_tables.go containing frozen property intervals and simple folds.
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
)

type Range struct{ Lo, Hi uint32 }

func main() {
	dir := "internal/regex/ucd/"
	props := map[string][]Range{}
	add := func(name string, lo, hi uint32) {
		key := norm(name)
		a := props[key]
		if n := len(a); n > 0 && a[n-1].Hi+1 == lo {
			a[n-1].Hi = hi
		} else {
			a = append(a, Range{lo, hi})
		}
		props[key] = a
	}

	// UnicodeData.txt -> exact general categories; major groups derived.
	major := map[byte]string{}
	f := mustOpen(dir + "UnicodeData.txt")
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		parts := strings.Split(line, ";")
		if len(parts) < 3 {
			continue
		}
		cp, err := strconv.ParseUint(parts[0], 16, 32)
		if err != nil {
			continue
		}
		gc := parts[2]
		lo, hi := uint32(cp), uint32(cp)
		if strings.HasSuffix(parts[1], ", First>") {
			// next line carries Last>
			if sc.Scan() {
				p2 := strings.Split(sc.Text(), ";")
				if v, e := strconv.ParseUint(p2[0], 16, 32); e == nil {
					hi = uint32(v)
				}
			}
		}
		add(gc, lo, hi)
		if len(gc) == 2 {
			major[gc[0]] = ""
			add(string(gc[0]), lo, hi)
		}
	}
	f.Close()

	parseRangeFile(mustOpen(dir+"Scripts.txt"), func(rang, name string) {
		lo, hi := parseCodeRange(rang)
		add("sc:"+name, lo, hi)
		add(name, lo, hi) // script bare names supported too
	})
	parseRangeFile(mustOpen(dir+"DerivedCoreProperties.txt"), func(rang, name string) {
		lo, hi := parseCodeRange(rang)
		add(name, lo, hi)
	})
	parseRangeFile(mustOpen(dir+"PropList.txt"), func(rang, name string) {
		lo, hi := parseCodeRange(rang)
		add(name, lo, hi)
	})

	// Simple case folding: status C and S only.
	folds := map[rune]rune{}
	ff := mustOpen(dir + "CaseFolding.txt")
	fs := bufio.NewScanner(ff)
	for fs.Scan() {
		line := fs.Text()
		if i := strings.Index(line, "#"); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		p := strings.Split(line, ";")
		if len(p) < 3 {
			continue
		}
		st := strings.TrimSpace(p[1])
		if st != "C" && st != "S" {
			continue
		}
		from, _ := strconv.ParseUint(strings.TrimSpace(p[0]), 16, 32)
		targets := strings.Fields(strings.TrimSpace(p[2]))
		if len(targets) == 1 {
			to, _ := strconv.ParseUint(targets[0], 16, 32)
			folds[rune(from)] = rune(to)
		}
	}
	ff.Close()

	// Derived aliases (PCRE-style shorthand properties).
	union := func(dst string, srcs ...string) {
		var all []Range
		for _, s := range srcs {
			all = append(all, props[norm(s)]...)
		}
		props[norm(dst)] = mergeRanges(all)
	}
	union("alpha", "Alphabetic")
	union("alnum", "Alphabetic", "Nd")
	union("digit", "Nd")
	union("punct", "P")
	union("upper", "Uppercase")
	union("lower", "Lowercase")
	union("space", "White_Space")
	union("blank", "Zs")
	props[norm("blank")] = mergeRanges(append(props[norm("blank")], Range{0x09, 0x09}))
	union("graph", "^Z", "^C") // replaced below properly
	// graph: everything except Z* and C* categories
	var notGraph []Range
	for _, g := range []string{"Z", "C"} {
		notGraph = append(notGraph, props[norm(g)]...)
	}
	props[norm("graph")] = complement(mergeRanges(notGraph))
	props[norm("print")] = props[norm("graph")]
	union("cntrl", "Cc")
	union("word", "L", "N")
	props[norm("word")] = mergeRanges(append(props[norm("word")], Range{'_', '_'}))
	// assigned = complement of Cn
	props[norm("assigned")] = complement(props[norm("Cn")])

	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	out, err := os.Create("internal/regex/uni_tables.go")
	check(err)
	defer out.Close()
	w := bufio.NewWriter(out)
	defer w.Flush()
	fmt.Fprintln(w, "// Code generated by internal/regex/gen/gen.go; DO NOT EDIT.")
	fmt.Fprintln(w, "// Source: Unicode 15.1.0 UCD (UnicodeData, Scripts, DerivedCoreProperties, PropList, CaseFolding).")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "package regex")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "type uniRange struct{ Lo, Hi rune }")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "// uniVersion is the pinned Unicode character database version.")
	fmt.Fprintln(w, `const uniVersion = "15.1.0"`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, "var uniProps = map[string][]uniRange{")
	for _, k := range keys {
		if k == "" {
			continue
		}
		fmt.Fprintf(w, "\t%q: {", k)
		for i, r := range props[k] {
			if i%6 == 0 {
				fmt.Fprintln(w)
				fmt.Fprint(w, "\t\t")
			}
			fmt.Fprintf(w, "{0x%X,0x%X}, ", r.Lo, r.Hi)
		}
		fmt.Fprintln(w, "\n\t},")
	}
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w)
	fk := make([]rune, 0, len(folds))
	for k := range folds {
		fk = append(fk, k)
	}
	sort.Slice(fk, func(i, j int) bool { return fk[i] < fk[j] })
	fmt.Fprintln(w, "var uniSimpleFold = map[rune]rune{")
	for _, k := range fk {
		fmt.Fprintf(w, "\t0x%X: 0x%X,\n", k, folds[k])
	}
	fmt.Fprintln(w, "}")
}

func parseRangeFile(f *os.File, cb func(rang, name string)) {
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.Index(line, "#"); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		p := strings.SplitN(line, ";", 2)
		if len(p) != 2 {
			continue
		}
		rang := strings.TrimSpace(p[0])
		name := strings.Fields(strings.TrimSpace(p[1]))[0]
		cb(rang, name)
	}
}

func parseCodeRange(s string) (lo, hi uint32) {
	s = strings.TrimSpace(s)
	if i := strings.Index(s, ".."); i >= 0 {
		a, _ := strconv.ParseUint(s[:i], 16, 32)
		b, _ := strconv.ParseUint(s[i+2:], 16, 32)
		return uint32(a), uint32(b)
	}
	v, _ := strconv.ParseUint(s, 16, 32)
	return uint32(v), uint32(v)
}

func mergeRanges(in []Range) []Range {
	sort.Slice(in, func(i, j int) bool {
		if in[i].Lo != in[j].Lo {
			return in[i].Lo < in[j].Lo
		}
		return in[i].Hi < in[j].Hi
	})
	var out []Range
	for _, r := range in {
		if n := len(out); n > 0 && r.Lo <= out[n-1].Hi+1 {
			if r.Hi > out[n-1].Hi {
				out[n-1].Hi = r.Hi
			}
			continue
		}
		out = append(out, r)
	}
	return out
}

func complement(in []Range) []Range {
	var out []Range
	next := uint32(0)
	max := uint32(0x10FFFF)
	for _, r := range in {
		if r.Lo > next {
			out = append(out, Range{next, r.Lo - 1})
		}
		if r.Hi+1 > next {
			next = r.Hi + 1
		}
	}
	if next <= max {
		out = append(out, Range{next, max})
	}
	return out
}

func norm(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "_", "")
	s = strings.TrimPrefix(s, "is")
	if s == "is" {
		s = ""
	}
	return s
}

func mustOpen(p string) *os.File {
	f, err := os.Open(p)
	check(err)
	return f
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
