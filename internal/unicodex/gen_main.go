// gen_main regenerates tables_generated.go from the host toolchain's pinned
// Unicode release. Run with: go run ./internal/unicodex/gen_main.go
//
// The generator itself reads the standard library tables, but the generated
// file is committed and the runtime packages never import "unicode".
