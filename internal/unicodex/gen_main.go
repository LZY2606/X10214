type pair = [2]rune

func tableToPairs(rt *unicode.RangeTable) []pair {
	m := map[rune]struct{}{}
	for _, r16 := range rt.R16 {
		if r16.Stride == 1 {
			for r := int64(r16.Lo); r <= int64(r16.Hi); r++ {
				m[rune(r)] = struct{}{}
			}
		} else {
			for r := int64(r16.Lo); r <= int64(r16.Hi); r += int64(r16.Stride) {
				m[rune(r)] = struct{}{}
			}
		}
	}
	for _, r32 := range rt.R32 {
		if r32.Stride == 1 {
			for r := int64(r32.Lo); r <= int64(r32.Hi); r++ {
				m[rune(r)] = struct{}{}
			}
		} else {
			for r := int64(r32.Lo); r <= int64(r32.Hi); r += int64(r32.Stride) {
				m[rune(r)] = struct{}{}
			}
		}
	}
	runes := make([]rune, 0, len(m))
	for r := range m {
		runes = append(runes, r)
	}
	sort.Slice(runes, func(i, j int) bool { return runes[i] < runes[j] })
	var out []pair
	for i := 0; i < len(runes); {
		lo := runes[i]
		hi := lo
		for i+1 < len(runes) && runes[i+1] == hi+1 {
			hi = runes[i+1]
			i++
		}
		out = append(out, pair{lo, hi})
		i++
	}
	return out
}

// buildFoldSets groups every rune reachable through unicode.SimpleFold into
// one equivalence class per fold cycle.
func buildFoldSets() (sets [][]rune, index map[rune]int) {
	index = map[rune]int{}
	addCycle := func(start rune) {
		if _, ok := index[start]; ok {
			return
		}
		var cyc []rune
		seen := map[rune]struct{}{}
		r := start
		for {
			if _, dup := seen[r]; dup {
				break
			}
			seen[r] = struct{}{}
			cyc = append(cyc, r)
			r = unicode.SimpleFold(r)
		}
		if len(cyc) <= 1 {
			index[start] = -1
			return
		}
		sort.Slice(cyc, func(i, j int) bool { return cyc[i] < cyc[j] })
		idx := len(sets)
		sets = append(sets, cyc)
		for _, c := range cyc {
			index[c] = idx
		}
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r == unicode.MaxRune {
			break
		}
		addCycle(r)
	}
	return sets, index
}

func emitPairs(buf *bytes.Buffer, name string, pairs []pair) {
	fmt.Fprintf(buf, "\t%q: {\n", name)
	for _, p := range pairs {
		fmt.Fprintf(buf, "\t\t{%d, %d},\n", p[0], p[1])
	}
	buf.WriteString("\t},\n")
}

func main() {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen_main.go; DO NOT EDIT.\n\n")
	buf.WriteString("package unicodex\n\n")
	fmt.Fprintf(&buf, "// Generated from Unicode release %s.\n\n", unicode.Version)
	buf.WriteString("var tables = map[string][][2]rune{\n")
	for _, name := range categoryNames {
		emitPairs(&buf, name, tableToPairs(categoryTable(name)))
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var whiteSpace = [][2]rune{\n")
	for _, p := range tableToPairs(unicode.White_Space) {
		fmt.Fprintf(&buf, "\t{%d, %d},\n", p[0], p[1])
	}
	buf.WriteString("}\n\n")

	sets, index := buildFoldSets()
	buf.WriteString("var foldSets = [][]rune{\n")
	for _, s := range sets {
		buf.WriteString("\t{")
		for _, r := range s {
			fmt.Fprintf(&buf, "%d, ", r)
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var foldIndex = map[rune]int{\n")
	keys := make([]rune, 0, len(index))
	for r, idx := range index {
		if idx >= 0 {
			keys = append(keys, r)
		}
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	for _, r := range keys {
		fmt.Fprintf(&buf, "\t%d: %d,\n", r, index[r])
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.WriteFile("internal/unicodex/tables_generated.go", buf.Bytes(), 0o644)
		os.Exit(1)
	}
	if err := os.WriteFile("internal/unicodex/tables_generated.go", formatted, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
